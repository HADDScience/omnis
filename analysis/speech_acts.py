"""발화 유형 규칙 분류. LLM 없이 정규식으로 분류하고, 표본 검수로 정확도를 함께 보고한다."""
import re

PATTERNS = [
    # 순서 중요: 위에서부터 먼저 매칭
    ("지시", [
        r"(해|돼|되|보내|올려|확인|정리|수정|작성|만들|준비|전달|공유|체크|검토|처리|진행|부탁)\s*(해\s*)?(주세요|주시|주실|줘|주라|줍니다)",
        r"(부탁\s*(드립|합)니다|부탁해)", r"(해\s*)?(주시면|주시겠|주실 수)",
        r"(하세요|하시길|바랍니다|바래요|해야\s*(합니다|해|될))",
        r"(필요합니다|필요해요|요청\s*드립)",
    ]),
    ("보고", [
        r"(완료|끝났|마무리|다\s*했|다\s*됐)", 
        r"(했습니다|하였습니다|드렸습니다|올렸습니다|보냈습니다|전달했|공유했|작성했|수정했|반영했)",
        r"(했어요|했어|드렸어요|올렸어요|보냈어요)",
        r"(입니다\.?$|였습니다)",
    ]),
    ("질문", [r"\?", r"(까요|나요|인가요|을까|ㄹ까|는지|어떤|어떻게|언제|어디|누가|뭐|무엇)\s*[?？]?\s*$"]),
    ("수락", [r"^\s*(넵+|네+|넹+|옙+|예+)[\s.!~]*$", r"(알겠습니다|알겠어요|알겠|확인했습니다|확인하겠|그렇게 하겠|진행하겠)"]),
    ("피드백", [r"(다시|재작업|수정\s*(해|바|필요)|바꿔|바꾸|아니라|말고|대신)", r"(좋(습니다|아요|네요)|굿|훌륭|감사)"]),
]
COMPILED = [(k, [re.compile(p) for p in ps]) for k, ps in PATTERNS]

URL = re.compile(r"https?://\S+")

def classify(msg: str) -> str:
    if not msg or msg.strip() == "":
        return "기타"
    # URL 안의 물음표가 질문으로 오탐되므로 먼저 제거
    m = URL.sub(" ", msg).strip()
    if not m:
        return "링크공유"
    for kind, regs in COMPILED:
        if any(r.search(m) for r in regs):
            return kind
    return "기타"
